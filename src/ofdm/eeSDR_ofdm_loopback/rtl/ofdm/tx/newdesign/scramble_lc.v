module scramble_lc (
    input   wire                            clk_Modulation                                  ,
    input   wire                            reset                                           ,
    input   wire    [15:0]                  packetlength                                    ,
    input   wire                            data_bit_valid                                  ,
    input   wire                            data_bit                                        ,
    output  reg                             scramble_bit_valid                              ,
    output  reg                             scramble_bit
);

    localparam                                  LP_SCRAMBLE_INT = 7'b0001111;

    reg                 [6:0]                   r_h1;
    reg                                         r_h2;
    reg                                         r_data_bit_dly;
    reg                                         r_scramble_bit_valid_dly;
    wire                                        w_scramble_bit_valid_end_flag;
    reg                 [15:0]                  r_data_bit_valid_cnt;
    reg                 [15:0]                  r_data_bit_zero_cnts_start;
    reg                 [15:0]                  r_data_bit_zero_cnts_end;

    // packetlength is the user payload length; the TX stream also contains the
    // four-byte FCS generated by crc32.  Tail bits therefore start after the
    // complete PSDU, not after the payload alone.
    // Metadata is stable before the first SERVICE bit. Register its arithmetic
    // separately from the per-bit tail comparator; no bit/valid latency changes.
    // Modulo-16-bit arithmetic matches the original expressions exactly.
    always @(posedge clk_Modulation) begin
        if (reset) begin
            r_data_bit_zero_cnts_start <= 0;
            r_data_bit_zero_cnts_end <= 0;
        end else begin
            r_data_bit_zero_cnts_start <= (packetlength << 3) + 16'd49;
            r_data_bit_zero_cnts_end <= (packetlength << 3) + 16'd54;
        end
    end

    assign w_scramble_bit_valid_end_flag = (~scramble_bit_valid) & r_scramble_bit_valid_dly;

    always @(posedge clk_Modulation) begin
        if (reset == 1'b1) begin
            r_h1 <= LP_SCRAMBLE_INT;
        end
        else if (w_scramble_bit_valid_end_flag == 1'b1) begin
            r_h1 <= LP_SCRAMBLE_INT;
        end
        else if (data_bit_valid == 1'b1) begin
            r_h1 <= {r_h1[5:0], r_h1[6] ^ r_h1[3]};
        end
    end

    always @(posedge clk_Modulation) begin
        if (reset == 1'b1) begin
            r_h2 <= 1'b0;
        end
        else if (w_scramble_bit_valid_end_flag == 1'b1) begin
            r_h2 <= 1'b0;
        end
        else if (data_bit_valid == 1'b1) begin
            r_h2 <= r_h1[6] ^ r_h1[3];
        end
    end

    always @(posedge clk_Modulation) begin
        if (reset == 1'b1) begin
            r_data_bit_dly <= 1'b0;
            scramble_bit_valid <= 1'b0;
            r_scramble_bit_valid_dly <= 1'b0;
        end
        else begin
            r_data_bit_dly <= data_bit;
            scramble_bit_valid <= data_bit_valid;
            r_scramble_bit_valid_dly <= scramble_bit_valid;
        end
    end

    always @(*) begin
        if (scramble_bit_valid == 1'b1) begin
            if (r_data_bit_valid_cnt >= r_data_bit_zero_cnts_start && r_data_bit_valid_cnt <= r_data_bit_zero_cnts_end) begin
                scramble_bit = 1'b0;
            end
            else begin
                scramble_bit = r_h2 ^ r_data_bit_dly;
            end
        end
        else begin
            scramble_bit = 1'b0;
        end
    end

    always @(posedge clk_Modulation) begin
        if (reset == 1'b1) begin
            r_data_bit_valid_cnt <= 'd0;
        end
        else if (w_scramble_bit_valid_end_flag) begin
            r_data_bit_valid_cnt <= 'd0;
        end
        else if (data_bit_valid == 1'b1) begin
            r_data_bit_valid_cnt <= r_data_bit_valid_cnt + 1'b1;
        end
    end

endmodule

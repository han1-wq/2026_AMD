#!/usr/bin/env python3
"""Stage the target-part real-IP simulation without reusing old IP wrappers."""
from pathlib import Path
import argparse
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--ip-dir', type=Path, required=True,
                    help='IP directory generated by build_project.tcl or build_dma.tcl')
parser.add_argument('--output-dir', type=Path, default=ROOT / 'sim/build')
args = parser.parse_args()
IP = args.ip_dir.resolve()
OUT = args.output_dir.resolve()
SRC = ROOT / 'rtl'
if not IP.exists():
    sys.exit(f'Generate IP using build_project.tcl first: {IP}')
OUT.mkdir(parents=True, exist_ok=True)
verilog = sorted(SRC.rglob('*.v'))
verilog = [p for p in verilog if p.name not in ('TOP.v', 'LED_TOP.v',
                                             'ad936x_phy_TOP.v', 'ad936x_ofdm_TOP.v',
                                             'ad936x_phy_tx.v',
                                             'ad936x_phy_rx.v')]
verilog += sorted(SRC.rglob('*.sv'))
vhdl = []
for xci in sorted(IP.glob('*/*.xci')):
    # Board-only clock/debug cores are not instantiated in the RF testbench.
    if xci.stem in ('clk_wiz_0', 'ila_0'):
        continue
    wrappers = list((xci.parent / 'sim').glob(xci.stem + '.v'))
    wrappers += list((xci.parent / 'sim').glob(xci.stem + '.vhd'))
    if len(wrappers) != 1:
        sys.exit(f'Expected one target-part IP wrapper for {xci}')
    (vhdl if wrappers[0].suffix == '.vhd' else verilog).append(wrappers[0])
    for mif in xci.parent.glob('*.mif'):
        shutil.copy2(mif, OUT / mif.name)
for mif in SRC.rglob('*.mif'):
    shutil.copy2(mif, OUT / mif.name)
verilog += [ROOT / 'sim/antenna_channel.v', ROOT / 'sim/tb_ofdm_rf_chain.v',
            Path('/tools/Xilinx/Vivado/2022.1/data/verilog/src/glbl.v')]
for filename, files in [('vlog.prj', verilog), ('vhdl.prj', vhdl)]:
    with (OUT / filename).open('w') as stream:
        for path in files:
            lang = {'.vhd': 'vhdl', '.sv': 'sv', '.v': 'verilog'}[path.suffix]
            stream.write(f'{lang} xil_defaultlib "{path}"\n')
        stream.write('nosort\n')
shutil.copy2(Path('/tools/Xilinx/Vivado/2022.1/data/xsim/xsim.ini'),
             OUT / 'xsim.ini')
print(f'PREPARED {OUT}: {len(verilog)} Verilog/SV and {len(vhdl)} VHDL')